--  مستوحى من بنية لوحة «بلدي»: مستخدمون + صلاحيات دقيقة + جلسات + سجل نشاط
-- ============================================================

-- ---------- المستخدمون ----------
create table if not exists public.app_users (
    id             bigint generated by default as identity primary key,
    email          text not null unique,
    password_hash  text not null,
    full_name      text not null,
    role           text not null default 'user' check (role in ('owner','admin','user')),
    is_active      boolean not null default true,
    created_by     bigint references public.app_users(id) on delete set null,
    created_at     timestamptz not null default now(),
    updated_at     timestamptz not null default now(),
    last_login_at  timestamptz,
    -- حصص وسياسات الحساب
    contract_limit integer,                 -- null = بلا حد
    expires_at     timestamptz              -- null = لا تنتهي
);

-- ---------- الجلسات ----------
create table if not exists public.app_sessions (
    id           bigint generated by default as identity primary key,
    user_id      bigint not null references public.app_users(id) on delete cascade,
    token_hash   text not null unique,
    expires_at   timestamptz not null,
    user_agent   text,
    ip           text,
    created_at   timestamptz not null default now(),
    last_seen_at timestamptz not null default now()
);
create index if not exists app_sessions_user_idx on public.app_sessions(user_id);
create index if not exists app_sessions_exp_idx  on public.app_sessions(expires_at);

-- ---------- الصلاحيات ----------
create table if not exists public.app_permissions (
    id         bigint generated by default as identity primary key,
    user_id    bigint not null references public.app_users(id) on delete cascade,
    permission text not null,
    granted    boolean not null default true,
    updated_at timestamptz not null default now(),
    unique (user_id, permission)
);
create index if not exists app_permissions_user_idx on public.app_permissions(user_id);

-- ---------- سجل النشاط ----------
create table if not exists public.app_audit_log (
    id          bigint generated by default as identity primary key,
    actor_id    bigint,
    actor_email text not null default 'system',
    action      text not null,
    entity      text not null default '',
    entity_id   text not null default '',
    details     jsonb not null default '{}'::jsonb,
    created_at  timestamptz not null default now()
);
create index if not exists app_audit_created_idx on public.app_audit_log(created_at desc);

-- ---------- رمز التحقق الفريد لكل تعاقد ----------
alter table public.contracts add column if not exists verify_token      text unique;

-- ---------- ربط العقود بمنشئها ----------
alter table public.contracts add column if not exists created_by        bigint;
alter table public.contracts add column if not exists created_by_name   text;
alter table public.contracts add column if not exists created_by_email  text;
create index if not exists contracts_created_by_idx on public.contracts(created_by);

-- ---------- RLS: الوصول عبر service_role فقط ----------
alter table public.app_users       enable row level security;
alter table public.app_sessions    enable row level security;
alter table public.app_permissions enable row level security;
alter table public.app_audit_log   enable row level security;

drop policy if exists app_users_service       on public.app_users;
drop policy if exists app_sessions_service    on public.app_sessions;
drop policy if exists app_permissions_service on public.app_permissions;
drop policy if exists app_audit_service       on public.app_audit_log;

create policy app_users_service       on public.app_users       for all to service_role using (true) with check (true);
create policy app_sessions_service    on public.app_sessions    for all to service_role using (true) with check (true);
create policy app_permissions_service on public.app_permissions for all to service_role using (true) with check (true);
create policy app_audit_service       on public.app_audit_log   for all to service_role using (true) with check (true);
